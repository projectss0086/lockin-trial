// 원장 입력을 하나의 사용자 메시지로 조립
export function buildUserMessage(input) {
  const { academy, student, learn, fork, scene, emotion, plan } = input;
  const lines = [];
  lines.push(`[학원 프로필]`);
  lines.push(`- 학원명: ${academy?.name || "학원"}`);
  if (academy?.owner_name) lines.push(`- 원장: ${academy.owner_name}`);
  if (academy?.subject) lines.push(`- 과목: ${academy.subject}`);
  lines.push("");
  lines.push(`[학생]`);
  lines.push(`- 이름: ${student?.name || ""}`);
  if (student?.gender) lines.push(`- 성별: ${student.gender === "여" ? "딸" : "아들"}`);
  if (student?.grade) lines.push(`- 학년: ${student.grade}`);
  if (student?.subject) lines.push(`- 수강 과목: ${student.subject}`);
  lines.push("");
  lines.push(`[학습 이야기]`);
  lines.push(`- 무엇을 배웠나: ${learn?.what || ""}`);
  lines.push(`- 어떻게 반응했나: ${learn?.react || ""}`);
  if (learn?.opinion) lines.push(`- 선생님 소감 / 앞으로의 학습계획: ${learn.opinion}`);
  lines.push("");
  if (fork === "growth") {
    lines.push(`[이번 달 담을 것: 성장 이야기]`);
    lines.push(`- 성장을 느낀 장면: ${scene || ""}`);
  } else {
    lines.push(`[이번 달 담을 것: 귀여운 에피소드]`);
    lines.push(`- 장면: ${scene || ""}`);
  }
  lines.push(`- 그때 선생님의 마음: ${emotion || "(선택 안 함)"}`);
  if (plan) lines.push(`- 이 부분 앞으로의 계획(원장 제시): ${plan}`);
  lines.push("");
  lines.push(`위 내용으로, 학부모에게 보낼 피드백의 '본문'을 써주세요. (첫인사·맺음말은 넣지 마세요.)`);
  return lines.join("\n");
}

// 받침 있으면 '이' 붙이는 애칭형 (수연→수연이, 영어→영어)
function hasJong(ch) { const c = (ch || "").charCodeAt(0); if (c < 0xac00 || c > 0xd7a3) return false; return (c - 0xac00) % 28 !== 0; }
function nickname(fn) { if (!fn) return fn; return hasJong(fn[fn.length - 1]) ? fn + "이" : fn; }

// 현재 월(한국 시간)에 맞는 계절 인사 — 계절마다 몇 개를 돌려 씀
function seasonGreeting(nick) {
  const m = new Date(Date.now() + 9 * 3600 * 1000).getUTCMonth() + 1; // KST 월
  let pool;
  if ([12, 1, 2].includes(m)) pool = [
    `추운 날씨에 감기 조심하시고, 따뜻하게 보내세요.`,
    `매서운 추위에 ${nick}도 어머님도 건강 유의하시길 바랍니다.`,
    `한 해 마무리 잘 하시고, 늘 건강하고 행복하시길 바랍니다.`,
  ];
  else if ([3, 4, 5].includes(m)) pool = [
    `일교차 큰 환절기, 감기 조심하시길 바랍니다.`,
    `따뜻한 봄날, ${nick}도 어머님도 건강하게 보내세요.`,
  ];
  else if ([6, 7, 8].includes(m)) pool = [
    `무더운 여름, ${nick}도 어머님도 건강하게 보내시길 바랍니다.`,
    `더위에 지치지 않게 건강 잘 챙기시길 바랍니다.`,
  ];
  else pool = [
    `쌀쌀해진 날씨에 감기 조심하시고, 환절기 건강 챙기세요.`,
    `선선한 가을, ${nick}도 어머님도 건강하게 보내세요.`,
  ];
  return pool[Math.floor(Math.random() * pool.length)];
}

// 고정 시그니처 인사/맺음말을 본문 앞뒤에 붙여 완성
// seasonLine: DB(season_greetings)에서 꺼낸 시적 계절 인사. 없으면 기본 문구로 대체.
export function wrapMessage(body, student, seasonLine) {
  const name = student?.name || "";
  const fn = name.length > 1 ? name.slice(1) : name; // 성 제외
  const nick = nickname(fn);
  const child = student?.gender === "여" ? "딸" : student?.gender === "남" ? "아들" : "아이";
  const greet = `어머님 안녕하세요. ^^우리 ${nick} 요즘 학습 근황 알려드립니다.`;
  const season = (seasonLine && seasonLine.trim()) || seasonGreeting(nick);
  const close = `${season} 예쁘고 귀한 ${child} ${nick}를 믿고 맡겨주시는 마음에 늘 감사드립니다.`;
  return `${greet}\n\n${(body || "").trim()}\n\n${close}`;
}

// 현재 계절 (KST 월 기준)
export function currentSeason() {
  const m = new Date(Date.now() + 9 * 3600 * 1000).getUTCMonth() + 1;
  if ([3, 4, 5].includes(m)) return "봄";
  if ([6, 7, 8].includes(m)) return "여름";
  if ([9, 10, 11].includes(m)) return "가을";
  return "겨울";
}
